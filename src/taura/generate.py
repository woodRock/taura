"""Rendering and parsing of generated text files.

Every generated .tex file is a provenance header followed by a body. The
header's content-hash covers the body, so a hand edit anywhere below the
header is detectable without the code repo.
"""

from __future__ import annotations

import re
from dataclasses import dataclass

from . import NAME
from .errors import TauraError
from .hashing import sha256_text
from .ledger import Format

HEADER_FIRST = f"% GENERATED BY {NAME} — DO NOT EDIT"
MACRO_PREFIX = f"{NAME}@"
RES_CMD = "res"

# ---- header ----------------------------------------------------------------


def render_header(artifact: str, code_commit: str, code_repo: str, results: dict[str, str], body: str) -> str:
    res = ", ".join(f"{k}@{v}" for k, v in sorted(results.items())) or "none"
    return (
        f"{HEADER_FIRST}\n"
        f"% artifact: {artifact}\n"
        f"% code: {code_commit} ({code_repo})\n"
        f"% results: {res}\n"
        f"% content-hash: {sha256_text(body)}\n"
    )


@dataclass
class Parsed:
    fields: dict[str, str]
    body: str

    @property
    def declared_hash(self) -> str | None:
        return self.fields.get("content-hash")

    @property
    def actual_hash(self) -> str:
        return sha256_text(self.body)


def parse(text: str) -> Parsed | None:
    """Split a generated file into header fields and body; None if the header is missing."""
    lines = text.split("\n")
    if not lines or lines[0] != HEADER_FIRST:
        return None
    fields: dict[str, str] = {}
    for i, line in enumerate(lines[1:], start=1):
        m = re.match(r"^% ([a-z-]+): (.*)$", line)
        if not m:
            return None
        fields[m.group(1)] = m.group(2)
        if m.group(1) == "content-hash":
            return Parsed(fields, "\n".join(lines[i + 1 :]))
    return None


# ---- macros ----------------------------------------------------------------

# \res{key}: the value, or a loud bold placeholder plus a LaTeX warning.
RES_PREAMBLE = rf"""\makeatletter
\DeclareRobustCommand\{RES_CMD}[1]{{%
  \@ifundefined{{{MACRO_PREFIX}#1}}%
    {{\PackageWarning{{{NAME}}}{{Undefined result key `\detokenize{{#1}}'}}%
     \textbf{{??\detokenize{{#1}}??}}}}%
    {{\@nameuse{{{MACRO_PREFIX}#1}}}}}}
\makeatother
"""

MACRO_LINE = re.compile(
    r"^\\expandafter\\def\\csname " + re.escape(MACRO_PREFIX) + r"(?P<key>[^\\]+)\\endcsname\{(?P<val>.*)\}$"
)


def render_macros(values: list[tuple[str, str]]) -> str:
    lines = [RES_PREAMBLE]
    for key, val in values:
        lines.append(rf"\expandafter\def\csname {MACRO_PREFIX}{key}\endcsname{{{val}}}" + "\n")
    return "".join(lines)


def parse_macros(body: str) -> dict[str, str]:
    out = {}
    for line in body.splitlines():
        m = MACRO_LINE.match(line)
        if m:
            out[m.group("key")] = m.group("val")
    return out


# ---- tables ----------------------------------------------------------------
#
# A table spec (from a script, or derived from artifacts.toml) is JSON:
#   {"columns": [{"label": "Method"}, {"label": "F1", "metric": "f1", "bold": "max"}],
#    "rows": [["MBA", {"mean": 0.912, "std": 0.008}], {"group": "\\textit{Drifted}"}, {"rule": true}, ...]}
# Cells are strings (LaTeX, used verbatim; "" for blank), numbers, {"mean", "std"} dicts, or null ("--").
# A row may instead be {"group": text} (a full-width \multicolumn heading) or {"rule": true}.
# Column labels are LaTeX, used verbatim.
#
# Layout options, from the spec or the artifact's table in artifacts.toml (the spec wins):
#   rules   = "booktabs" | "hline"
#   colspec = "@{}lrr@{}"         (default: l for text columns, c for numeric)
#   bold    = "max" | "min"       (columns override with "bold": "max" | "min" | "none")
#   bold_by = "column" | "row"    (best per column, or best across the bolded columns of each row)
#   group_align = "l"             (alignment of {"group": ...} rows)

PM = r" $\pm$ "
MISSING = "--"
LAYOUT_KEYS = ("rules", "colspec", "bold", "bold_by", "group_align")
RULES = {"booktabs": (r"\toprule", r"\midrule", r"\bottomrule"), "hline": (r"\hline",) * 3}
RULE_LINES = {r"\toprule", r"\midrule", r"\bottomrule", r"\hline"}


def _num(fmt: Format, x) -> str:
    s = fmt.render(x)
    return "$-$" + s[1:] if s.startswith("-") else s


def _render_cell(cell, fmt: Format) -> tuple[str, str | None]:
    """(LaTeX text, the displayed number used for bolding or None)."""
    if cell is None:
        return MISSING, None
    if isinstance(cell, str):
        return cell, None
    if isinstance(cell, dict):
        if "mean" not in cell:
            raise TauraError(f"table cell {cell!r} needs a `mean`")
        mean = fmt.render(cell["mean"])
        text = _num(fmt, cell["mean"])
        if cell.get("std") is not None:
            text += PM + _num(fmt, cell["std"])
        return text, mean
    if isinstance(cell, (int, float)) and not isinstance(cell, bool):
        return _num(fmt, cell), fmt.render(cell)
    raise TauraError(f"unsupported table cell {cell!r}")


def layout(spec: dict, options: dict) -> dict:
    lay = {k: options[k] for k in LAYOUT_KEYS if k in options}
    lay.update({k: spec[k] for k in LAYOUT_KEYS if k in spec})
    lay.setdefault("rules", "booktabs")
    lay.setdefault("bold_by", "column")
    lay.setdefault("group_align", "l")
    if lay["rules"] not in RULES:
        raise TauraError(f"table rules must be one of {', '.join(RULES)}")
    if lay["bold_by"] not in ("column", "row"):
        raise TauraError("table bold_by must be \"column\" or \"row\"")
    if lay.get("bold") not in (None, "max", "min"):
        raise TauraError("table bold must be \"max\" or \"min\"")
    return lay


def render_table(spec: dict, formats, options: dict) -> tuple[str, list[str], str]:
    """Render a tabular. Returns (body, per-column bold rule "max"/"min"/"", bold_by)."""
    columns = spec.get("columns")
    rows = spec.get("rows")
    if not isinstance(columns, list) or not columns or not isinstance(rows, list):
        raise TauraError("table spec needs non-empty `columns` and a `rows` list")
    lay = layout(spec, options)
    ncol = len(columns)
    for r in rows:
        if isinstance(r, dict):
            if not ("group" in r or r.get("rule")):
                raise TauraError(f"table row {r!r} must be a list of cells, {{\"group\": ...}} or {{\"rule\": true}}")
        elif not isinstance(r, list) or len(r) != ncol:
            raise TauraError(f"table row {r!r} must have {ncol} cells")

    col_fmt = [formats(c.get("metric")) for c in columns]
    data = [i for i, r in enumerate(rows) if isinstance(r, list)]
    cells: dict[int, list[tuple[str, str | None]]] = {
        i: [_render_cell(cell, col_fmt[j]) for j, cell in enumerate(rows[i])] for i in data
    }

    numeric = [any(cells[i][j][1] is not None for i in data) for j in range(ncol)]
    bold_rules = []
    for j, c in enumerate(columns):
        rule = c.get("bold", lay.get("bold") if numeric[j] else None)
        if rule in (None, "none", ""):
            rule = ""
        if rule not in ("", "max", "min"):
            raise TauraError(f"column {c.get('label')!r}: bold must be max, min or none")
        bold_rules.append(rule)

    # Bold by the *displayed* value, so ties at the printed precision are all bold.
    def embolden(group: list[tuple[int, int]], rule: str) -> None:
        shown = [float(cells[i][j][1]) for i, j in group if cells[i][j][1] is not None]
        if not shown:
            return
        best = max(shown) if rule == "max" else min(shown)
        for i, j in group:
            text, val = cells[i][j]
            if val is not None and float(val) == best:
                cells[i][j] = (rf"\textbf{{{text}}}", val)

    if lay["bold_by"] == "column":
        for j, rule in enumerate(bold_rules):
            if rule:
                embolden([(i, j) for i in data], rule)
    else:
        active = {r for r in bold_rules if r}
        if len(active) > 1:
            raise TauraError("bold_by = \"row\" needs one direction (max or min) across columns")
        if active:
            rule = active.pop()
            for i in data:
                embolden([(i, j) for j in range(ncol) if bold_rules[j]], rule)

    top, mid, bottom = RULES[lay["rules"]]
    colspec = lay.get("colspec") or "".join("c" if numeric[j] else "l" for j in range(ncol))
    out = [rf"\begin{{tabular}}{{{colspec}}}", top]
    out.append(" & ".join(str(c.get("label", "")) for c in columns) + r" \\")
    out.append(mid)
    for i, r in enumerate(rows):
        if isinstance(r, dict):
            if r.get("rule"):
                out.append(mid)
            else:
                out.append(rf"\multicolumn{{{ncol}}}{{{lay['group_align']}}}{{{r['group']}}} \\")
        else:
            out.append(" & ".join(text for text, _ in cells[i]) + r" \\")
    out += [bottom, r"\end{tabular}%"]  # no space after the tabular when \input inside \centering
    return "\n".join(out) + "\n", bold_rules, lay["bold_by"]


def parse_table(body: str) -> tuple[list[str], list[list[str]]]:
    """(header cells, data rows) from a generated tabular; group headings and rules are skipped."""
    lines = body.splitlines()
    rule_at = [i for i, l in enumerate(lines) if l.strip() in RULE_LINES]
    if len(rule_at) < 3:
        return [], []

    def cells(line: str) -> list[str]:
        line = re.sub(r"\s*\\\\\s*$", "", line)
        return [c.strip() for c in re.split(r"(?<!\\)&", line)]

    first, second, last = rule_at[0], rule_at[1], rule_at[-1]
    header = cells(" ".join(lines[first + 1 : second]))
    rows = [
        cells(l) for l in lines[second + 1 : last]
        if l.strip() and l.strip() not in RULE_LINES and not l.lstrip().startswith(r"\multicolumn")
    ]
    return header, rows


def plain(cell: str) -> str:
    """A table cell as a reader would see it: 0.912 ± 0.008."""
    s = re.sub(r"\\textbf\{(.*)\}", r"\1", cell)
    return s.replace(PM.strip(), "±").replace("$-$", "-")


def is_bold(cell: str) -> bool:
    return cell.startswith(r"\textbf{")


def leading_number(cell: str) -> float | None:
    m = re.match(r"^-?\d+(?:\.\d+)?", plain(cell))
    return float(m.group(0)) if m else None
